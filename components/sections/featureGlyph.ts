const BY_TITLE = new Map<string, GlyphName>(
  Object.entries(BY_GLYPH).flatMap(([glyph, titles]) =>
    titles.map((t): [string, GlyphName] => [t, glyph as GlyphName]),
  ),
);

/** Старые ключи icon (components/ui/Icon) - запасной вариант для новых пунктов. */
const ICON_FALLBACK: Record<string, GlyphName> = {
  search: "keywords",
  target: "tracking",
  window: "site",
  chart: "report",
  gauge: "speed",
  shield: "quality",
  spark: "system",
  users: "team",
  trending: "path",
  doc: "content",
  rocket: "ad",
  check: "audit",
  arrow: "path",
};

export function featureGlyph(f: Feature): GlyphName {
  return BY_TITLE.get(f.title) ?? ICON_FALLBACK[f.icon ?? ""] ?? "audit";
}
