export function getLanding(
  channel: string,
  slug: string,
): ServiceLanding | undefined {
  return landings.find((l) => l.channel === channel && l.slug === slug);
}

/** Гео-нейтральные подуслуги канала: пункты дропдауна и блок «Подуслуги» на хабе. */
export function subservicesOf(channel: string): ServiceLanding[] {
  return landings.filter((l) => l.channel === channel && l.kind === "subservice");
}

/** Городовые страницы услуги: самого канала (parent не задан) или его подуслуги. */
export function cityLandingsOf(channel: string, parent?: string): ServiceLanding[] {
  return landings.filter(
    (l) => l.channel === channel && l.kind !== "subservice" && l.parent === parent,
  );
}
